/**
 * Materializes frozen docs snapshots under src/docs/versions/<semver>/ before build:docs.
 *
 * Policy: new snapshots only on minor or major package bumps (or first release).
 * Patch bumps reuse the latest snapshot; live docs still build from current source.
 * Set FORCE_DOCS_SNAPSHOT=1 to create a snapshot on a patch (exceptional cases).
 *
 * @see docs/docs-version-snapshots.md
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  computeRetainedSnapshotVersions,
  shouldMaterializeDocsSnapshot,
} from './lib/docs-version-policy.mjs'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const versionsRoot = path.join(root, 'src/docs/versions')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const currentVersion = pkg.version
const forceSnapshot = process.env.FORCE_DOCS_SNAPSHOT === '1'

const SEMVER_DIR_RE = /^\d+\.\d+\.\d+$/

function compareSemverDesc(a, b) {
  const pa = a.split('.').map(Number)
  const pb = b.split('.').map(Number)
  for (let i = 0; i < 3; i += 1) {
    if (pa[i] !== pb[i]) return pb[i] - pa[i]
  }
  return 0
}

function listSnapshotVersions() {
  return fs
    .readdirSync(versionsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && SEMVER_DIR_RE.test(entry.name))
    .map((entry) => entry.name)
    .sort(compareSemverDesc)
}

function renderVersionIndex(version) {
  return `// Generated by scripts/sync-docs-version-snapshot.mjs for @chghealthcare/unified-design-system v${version}.
import { HouseIcon, cn } from '@chghealthcare/unified-design-system'
import type { ComponentProps } from 'react'
import { CATALOG_META } from '../../catalog-meta'
import { getShadcnComponentMeta } from '../../shadcn-component-meta'
import { getShadcnComponentProps } from '../../shadcn-component-props'
import { getShadcnExamples } from '../../shadcn-examples'
import {
  SHADCN_UI_SLUGS,
  formatShadcnComponentName,
  getShadcnDocsUrl,
} from '../../shadcn-ui-registry'
import { getCustomSections } from '../../sections/custom-sections'
import { createDocsVersionBundle } from '../create-bundle'

function WelcomeMenuIcon(props: ComponentProps<typeof HouseIcon>) {
  const { className, ...rest } = props
  return <HouseIcon {...rest} size={32} className={cn('shrink-0', className)} />
}

const bundle = createDocsVersionBundle({
  id: '${version}',
  catalog: CATALOG_META,
  shadcnSlugs: SHADCN_UI_SLUGS,
  getCustomSections,
  getShadcnComponentMeta,
  getShadcnComponentProps,
  getShadcnExamples,
  formatShadcnComponentName,
  getShadcnDocsUrl,
  welcomeMenuIcon: WelcomeMenuIcon,
})

export default bundle
`
}

function renderManifest(versions, defaultVersion) {
  const ordered = [...versions].sort((a, b) => {
    if (a === defaultVersion) return -1
    if (b === defaultVersion) return 1
    return compareSemverDesc(a, b)
  })

  const versionEntries = ordered
    .map((version) => `    {\n      id: '${version}',\n      label: \`Documentation - v${version}\`,\n    },`)
    .join('\n')

  return `// Generated by scripts/sync-docs-version-snapshot.mjs — do not edit manually.
import type { DocsVersionId, DocsVersionManifestEntry } from './types'

/** Installed package version this docs build documents (from package.json at build time). */
export const DOCS_PACKAGE_VERSION = __DOCS_VERSION__ as DocsVersionId

export const DOCS_VERSION_MANIFEST = {
  /** Frozen snapshot loaded by default (latest minor/major docs release, not every patch). */
  defaultVersion: '${defaultVersion}' as DocsVersionId,
  versions: [
${versionEntries}
  ] satisfies DocsVersionManifestEntry[],
}

export function getDocsVersionManifest() {
  return DOCS_VERSION_MANIFEST
}

export function getDocsVersionOptions(): DocsVersionManifestEntry[] {
  return DOCS_VERSION_MANIFEST.versions
}

/** Newest snapshot in the manifest (first entry, semver-desc). */
export function getLatestDocsVersionId(): DocsVersionId {
  return DOCS_VERSION_MANIFEST.versions[0]?.id ?? DOCS_VERSION_MANIFEST.defaultVersion
}

/** False until a second minor/major docs snapshot exists (hides sidebar version selector). */
export function shouldShowDocsVersionSelector(): boolean {
  return DOCS_VERSION_MANIFEST.versions.length >= 2
}
`
}

function pruneSnapshotDirectories(retainedVersions) {
  const retained = new Set(retainedVersions)
  for (const entry of fs.readdirSync(versionsRoot, { withFileTypes: true })) {
    if (!entry.isDirectory() || !SEMVER_DIR_RE.test(entry.name)) continue
    if (retained.has(entry.name)) continue
    const target = path.join(versionsRoot, entry.name)
    fs.rmSync(target, { recursive: true, force: true })
    console.log(`sync-docs-version-snapshot: removed obsolete snapshot v${entry.name}`)
  }
}

function renderResolveLoaders(versions) {
  const loaderEntries = versions
    .map((version) => `  '${version}': () => import('./${version}'),`)
    .join('\n')

  return `// Generated by scripts/sync-docs-version-snapshot.mjs — do not edit manually.
import type { DocsVersionBundle, DocsVersionId } from './types'

export const docsVersionBundleLoaders: Record<
  DocsVersionId,
  () => Promise<{ default: DocsVersionBundle }>
> = {
${loaderEntries}
}
`
}

const snapshotVersions = listSnapshotVersions()
const latestSnapshotVersion = snapshotVersions[0]
const snapshotDir = path.join(versionsRoot, currentVersion)
const snapshotExists = fs.existsSync(path.join(snapshotDir, 'index.tsx'))

const decision = shouldMaterializeDocsSnapshot({
  packageVersion: currentVersion,
  latestSnapshotVersion,
  snapshotExists,
  force: forceSnapshot,
})

if (decision.write) {
  fs.mkdirSync(snapshotDir, { recursive: true })
  fs.writeFileSync(path.join(snapshotDir, 'index.tsx'), renderVersionIndex(currentVersion))
  fs.writeFileSync(
    path.join(snapshotDir, 'snapshot.json'),
    JSON.stringify(
      {
        packageVersion: currentVersion,
        generatedAt: new Date().toISOString(),
        materializeReason: decision.reason,
      },
      null,
      2,
    ) + '\n',
  )
} else {
  console.log(
    `sync-docs-version-snapshot: skipped new snapshot for v${currentVersion} (${decision.reason}); reusing latest docs v${latestSnapshotVersion ?? 'none'}.`,
  )
}

const allSnapshotVersions = listSnapshotVersions()
if (!allSnapshotVersions.length) {
  console.error('sync-docs-version-snapshot: no documentation snapshots exist. Bump minor/major or set FORCE_DOCS_SNAPSHOT=1.')
  process.exit(1)
}

const manifestVersions = computeRetainedSnapshotVersions(allSnapshotVersions)
pruneSnapshotDirectories(manifestVersions)

const defaultVersion = manifestVersions.includes(currentVersion)
  ? currentVersion
  : manifestVersions[0]

fs.writeFileSync(path.join(versionsRoot, 'manifest.ts'), renderManifest(manifestVersions, defaultVersion))
fs.writeFileSync(path.join(versionsRoot, 'resolve-loaders.generated.ts'), renderResolveLoaders(manifestVersions))

if (decision.write) {
  console.log(
    `sync-docs-version-snapshot: ${snapshotExists ? 'refreshed' : 'created'} snapshot v${currentVersion} (${decision.reason}); docs default v${defaultVersion}.`,
  )
} else {
  console.log(`sync-docs-version-snapshot: manifest default docs v${defaultVersion} (package v${currentVersion}).`)
}
