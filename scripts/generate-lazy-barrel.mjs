/**
 * Generates dist/lazy-index.cjs — a CJS proxy barrel for consumer test environments.
 *
 * When a consumer's Vitest or Jest config enables the "test" export condition
 * (resolve.conditions / customExportConditions), Node resolves
 * `@chghealthcare/unified-design-system` to this file instead of dist/index.js.
 * Each component module is require()d only on first access of one of its named
 * exports, so a test that imports only Button never loads recharts, cmdk, vaul,
 * react-day-picker, or any of the other 80 sibling component modules.
 *
 * Invoked from `build:lib` after Vite/tsc/`prepare-package` and before
 * `generate-subpath-exports --verify-dist` (that check requires this file).
 * Reads dist/index.js to derive the mapping.
 *
 * The "test" condition in package.json points to this file; update the
 * generate script if new component files are added (or re-run it).
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const indexPath = path.join(root, "dist", "index.js")
const outPath = path.join(root, "dist", "lazy-index.cjs")

if (!fs.existsSync(indexPath)) {
  console.error("dist/index.js not found — run `npm run build:lib` first.")
  process.exit(1)
}

const src = fs.readFileSync(indexPath, "utf8")

// ── Step 1: map every local alias used in imports → { modPath, originalName }
// import { X as a, Y as b } from './path'
const importRe = /^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]/gm
/** @type {Map<string, { modPath: string; originalName: string }>} */
const aliasToMod = new Map()

let m
while ((m = importRe.exec(src)) !== null) {
  const modPath = m[2]
  for (const spec of m[1].split(",")) {
    const parts = spec.trim().split(/\s+as\s+/)
    const originalName = parts[0].trim()
    const localAlias = parts.length > 1 ? parts[1].trim() : originalName
    aliasToMod.set(localAlias, { modPath, originalName })
  }
}

// ── Step 2: map every final exported name → { modPath, originalName }
// export { a as Accordion, b as AccordionContent, ... }
const exportRe = /export\s*\{([^}]+)\}/s
const exportMatch = exportRe.exec(src)
if (!exportMatch) {
  console.error("No export block found in dist/index.js — unexpected build output format.")
  process.exit(1)
}

/** @type {Map<string, { modPath: string; originalName: string }>} */
const exportedNameToMod = new Map()

for (const spec of exportMatch[1].split(",")) {
  const parts = spec.trim().split(/\s+as\s+/)
  const localAlias = parts[0].trim()
  const exportedAs = parts.length > 1 ? parts[1].trim() : localAlias
  const entry = aliasToMod.get(localAlias)
  if (entry) {
    exportedNameToMod.set(exportedAs, entry)
  }
}

// ── Step 3: group exported names by module path
/** @type {Map<string, { exportedName: string; originalName: string }[]>} */
const modToExports = new Map()

for (const [exportedName, { modPath, originalName }] of exportedNameToMod) {
  if (!modToExports.has(modPath)) modToExports.set(modPath, [])
  modToExports.get(modPath).push({ exportedName, originalName })
}

// ── Step 4: emit the lazy CJS barrel
// Converts ESM relative paths (./components/ui/button.js) →
// CJS-compatible dist-relative paths (./components/ui/button.cjs)
function esmToCjsPath(esmPath) {
  return esmPath.replace(/\.js$/, ".cjs")
}

const lines = [
  "/**",
  " * Lazy CJS proxy barrel — generated by scripts/generate-lazy-barrel.mjs.",
  " *",
  " * Activated via the \"test\" export condition in package.json:",
  " *   Vitest:  resolve: { conditions: [\"test\"] }",
  " *   Jest:    testEnvironmentOptions: { customExportConditions: [\"test\"] }",
  " *            (or resolver that honours \"test\" condition)",
  " *",
  " * Each component module is require()d on first property access, so tests",
  " * that import only Button never pay the load cost of recharts, cmdk, vaul, etc.",
  " * DO NOT edit manually — re-run `node scripts/generate-lazy-barrel.mjs`.",
  " */",
  "",
  "\"use strict\";",
  "",
  "// Map: exported name → lazy loader",
  "const _loaders = {",
]

// Sort for deterministic output
const sortedMods = [...modToExports.entries()].sort(([a], [b]) => a.localeCompare(b))

for (const [modPath, exports] of sortedMods) {
  const cjsPath = esmToCjsPath(modPath)
  for (const { exportedName, originalName } of exports.sort((a, b) =>
    a.exportedName.localeCompare(b.exportedName),
  )) {
    const getter =
      exportedName === originalName
        ? `function() { return require("${cjsPath}").${originalName}; }`
        : `function() { return require("${cjsPath}").${originalName}; }`
    lines.push(`  ${JSON.stringify(exportedName)}: ${getter},`)
  }
}

lines.push("};", "")
lines.push(
  "// Module cache: once a CJS module is required once, Node caches it — subsequent",
  "// property accesses on the same module are free.",
  "module.exports = new Proxy({}, {",
  "  get(_, key) {",
  '    if (typeof key !== "string") return undefined;',
  "    const loader = _loaders[key];",
  "    return loader ? loader() : undefined;",
  "  },",
  "  has(_, key) {",
  "    return key in _loaders;",
  "  },",
  "  ownKeys() {",
  "    return Object.keys(_loaders);",
  "  },",
  "  getOwnPropertyDescriptor(_, key) {",
  "    if (key in _loaders) return { configurable: true, enumerable: true };",
  "    return undefined;",
  "  },",
  "});",
  "",
)

fs.writeFileSync(outPath, lines.join("\n"), "utf8")

const exportCount = exportedNameToMod.size
const modCount = modToExports.size
console.log(
  `generate-lazy-barrel: wrote dist/lazy-index.cjs — ${exportCount} exports across ${modCount} modules.`,
)
